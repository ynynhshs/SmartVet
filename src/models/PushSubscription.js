const mongoose = require('mongoose');

const pushSubscriptionSchema = new mongoose.Schema(
    {
        // Owner who owns this browser subscription.
        userId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: 'User',
            required: [true, 'User is required.'],
            index: true
        },

        // Unique push service endpoint for this browser subscription.
        endpoint: {
            type: String,
            required: [true, 'Endpoint is required.'],
            unique: true,
            trim: true,
            maxlength: 500
        },

        // When the push service says the subscription expires (nullable).
        expirationTime: {
            type: Date,
            default: null
        },

        // Encryption keys generated by the browser.
        keys: {
            p256dh: { type: String, required: [true, 'p256dh key is required.'] },
            auth: { type: String, required: [true, 'auth key is required.'] }
        }
    },
    {
        timestamps: true,
        versionKey: false
    }
);

module.exports = mongoose.model(
    'PushSubscription',
    pushSubscriptionSchema
);
